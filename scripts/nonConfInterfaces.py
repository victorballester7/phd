#!/usr/bin/env python3
"""
Regenerate the <MOVEMENT> block (zones + non-conforming interfaces) and the EXPANSIONS composite range of a
Nektar++ session file from the composites of a mesh generated with a non-conforming .geo file
(e.g. src/comGapRe1000Ma0.8/baseflow/dns/d4_w19/mesh.geo).

Convention of the .geo file:
  - Physical Surface(100 + i) -> domain D[i] -> zone i (100: first layer of quads, 101: gap, 102 + k: strip k)
  - Physical Curve(200 + 2*j) / (201 + 2*j): lower / upper side of interface j, with j = k*nSeg + i
    (k: interface between strip k-1 (or the first layer of quads if k = 0) and strip k, i: segment in x)

Usage: nonConfInterfaces.py [mesh.xml] [session.xml]
"""

import re
import sys

mesh_file = sys.argv[1] if len(sys.argv) > 1 else "mesh.xml"
session_file = sys.argv[2] if len(sys.argv) > 2 else "session.xml"

mesh = open(mesh_file).read()
domains = sorted(int(d) for d in re.findall(r'<D ID="(\d+)">', mesh))
iface_comps = sorted(int(c) for c in re.findall(r'<C ID="(\d+)">', mesh) if int(c) >= 200)

nDomains = len(domains)
nStrips = nDomains - 2
nPairs = len(iface_comps) // 2
if nStrips < 1 or nPairs == 0 or nPairs % nStrips != 0:
    sys.exit(f"Unexpected composites: {nDomains} domains, {len(iface_comps)} interface composites")
nSeg = nPairs // nStrips

lines = [
    "  <!-- non-conforming interfaces (generated by scripts/nonConfInterfaces.py): zone i = D[i] = C[100+i];",
    f"       {nStrips} interfaces in y, each split in {nSeg} segments in x; segment j joins C[200+2j] (lower side) and C[201+2j] (upper side) -->",
    "  <MOVEMENT>",
    "    <ZONES>",
]
lines += [f'      <FIXED ID="{i}" DOMAIN="D[{i}]" />' for i in range(nDomains)]
lines += ["    </ZONES>", "    <INTERFACES>"]
for j in range(nPairs):
    k = j // nSeg
    left = 0 if k == 0 else k + 1
    right = k + 2
    lines += [
        f'      <INTERFACE NAME="if{k}_{j % nSeg}">',
        f'        <LEFT  ID="{left}" BOUNDARY="C[{200 + 2 * j}]" />',
        f'        <RIGHT ID="{right}" BOUNDARY="C[{201 + 2 * j}]" />',
        "      </INTERFACE>",
    ]
lines += ["    </INTERFACES>", "  </MOVEMENT>"]
movement = "\n".join(lines)

session = open(session_file).read()
pattern = re.compile(r"[ \t]*<!--[^<]*?non-conforming interfaces.*?-->\s*<MOVEMENT>.*?</MOVEMENT>|[ \t]*<MOVEMENT>.*?</MOVEMENT>", re.S)
if pattern.search(session):
    session = pattern.sub(lambda _: movement, session, count=1)
else:
    session = session.replace("</EXPANSIONS>", "</EXPANSIONS>\n\n" + movement, 1)

session = re.sub(r'(<E COMPOSITE=")C\[[^\]]*\]', rf"\1C[100-{100 + nDomains - 1}]", session, count=1)
open(session_file, "w").write(session)
print(f"{session_file}: {nDomains} zones, {nPairs} interfaces ({nStrips} x {nSeg} segments)")
