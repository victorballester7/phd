#!/usr/bin/env python3
"""
Rewrite the volume-forcing ("Noise" FUNCTION) of a Nektar++ session file.

The forcing derives from a stream function
    psi = Amplitude * exp(-(weightX*(x-x0)^2 + weightY*(y-y0)^2)) * s
    u   =  dpsi/dy = -2*weightY*(y-y0)*Amplitude*exp(...)*s
    v   = -dpsi/dx =  2*weightX*(x-x0)*Amplitude*exp(...)*s
weightX = weightY = weight recovers the original isotropic Gaussian.

Signal types s:
  awgn       independent awgn(1.0) for u and v at every quadrature point and
             time step (same as the original setup; not divergence free).
  multisine  one coherent signal s(t) = sum_k a_k cos(w_k t + phi_k) for the
             whole source and both components (divergence free).
             Spectrum PSD ~ w^slope (slope=0: flat, slope=-5/3: FST-like),
             random phases with fixed seed, normalised to rms(s) = 1.
             Frequencies/amplitudes/phases are saved to noise_multisine.dat
             next to the session file.

Amplitude defaults to 0.05/sqrt(weightY), which keeps the peak u-forcing
equal to the original weight=100, Amplitude=0.5/weight setup (the solver is
linear, so this only keeps the signal levels comparable; N is unaffected).

Usage:
  makeNoiseForcing.py session.xml envelope  --wx 1 --wy 1 [--x0 -95 --y0 0.5]
  makeNoiseForcing.py session.xml multisine --slope 0 --wmin 0.01 --wmax 0.25 \
                                            --nfreq 25 --seed 1 [--wx 100 --wy 100]
"""

import argparse
import os
import re
import sys

import numpy as np


def parseArgs():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("session", help="session.xml to modify in place")
    parser.add_argument("signal", choices=["envelope", "multisine"],
                        help="envelope: awgn signal (original); multisine: coherent band-limited signal")
    parser.add_argument("--x0", type=float, default=-95.0)
    parser.add_argument("--y0", type=float, default=0.5)
    parser.add_argument("--wx", type=float, default=100.0, help="streamwise Gaussian weight (1/length^2)")
    parser.add_argument("--wy", type=float, default=100.0, help="wall-normal Gaussian weight (1/length^2)")
    parser.add_argument("--amplitude", type=str, default=None,
                        help="Amplitude expression (default: 0.05/sqrt(weightY))")
    parser.add_argument("--wmin", type=float, default=0.01, help="lowest angular frequency")
    parser.add_argument("--wmax", type=float, default=0.25, help="highest angular frequency")
    parser.add_argument("--nfreq", type=int, default=25, help="number of equally spaced frequencies")
    parser.add_argument("--slope", type=float, default=0.0, help="PSD ~ w^slope (0 flat, -5/3 FST-like)")
    parser.add_argument("--seed", type=int, default=1, help="seed for the random phases")
    return parser.parse_args()


def multisine(args):
    w = np.linspace(args.wmin, args.wmax, args.nfreq)
    a = w ** (args.slope / 2.0)          # amplitude ~ sqrt(PSD) for equal spacing
    a /= np.sqrt(0.5 * np.sum(a ** 2))   # rms(s) = 1
    phi = np.random.default_rng(args.seed).uniform(0.0, 2.0 * np.pi, args.nfreq)
    expr = "(" + " + ".join(f"{ak:.10g}*cos({wk:.10g}*t + {pk:.10g})" for ak, wk, pk in zip(a, w, phi)) + ")"
    return w, a, phi, expr


def parametersBlock(args, indent):
    amplitude = args.amplitude if args.amplitude else "0.05/sqrt(weightY)"
    lines = [
        "<!--Disturbance strip parameters-->",
        f"<P> x0        = {args.x0:g}                     </P>",
        f"<P> y0        = {args.y0:g}                  </P> ",
        f"<P> weightX         = {args.wx:g}                  </P> <!-- streamwise weight of the Gaussian function !-->",
        f"<P> weightY         = {args.wy:g}                  </P> <!-- wall-normal weight of the Gaussian function !-->",
        f"<P> Amplitude       = {amplitude}                   </P> ",
    ]
    return lines[0] + "".join("\n" + indent + "  " + l for l in lines[1:]) + "\n"


def noiseBlock(signalU, signalV, indent):
    envelope = "Amplitude*exp(-(weightX*((x-x0)^2) + weightY*((y-y0)^2)))"
    # "--" is not allowed inside XML comments
    cmd = "makeNoiseForcing.py " + " ".join(sys.argv[2:]).replace("--", "")
    lines = [
        '<FUNCTION NAME="Noise">',
        f"  <!-- generated by: {cmd} !-->",
        f'  <E VAR="u" VALUE="-2*weightY*(y-y0)*{envelope}*{signalU}" />',
        f'  <E VAR="v" VALUE="2*weightX*(x-x0)*{envelope}*{signalV}" />',
        '  <E VAR="p" VALUE="0" />',
        "</FUNCTION>",
    ]
    return ("\n" + indent).join(lines)


def main():
    args = parseArgs()
    with open(args.session) as f:
        text = f.read()

    if args.signal == "envelope":
        signalU = signalV = "awgn(1.0)"
    else:
        w, a, phi, signalU = multisine(args)
        signalV = signalU
        out = os.path.join(os.path.dirname(os.path.abspath(args.session)), "noise_multisine.dat")
        np.savetxt(out, np.column_stack([w, a, phi]),
                   header=f"seed={args.seed} slope={args.slope:g} rms=1\nomega amplitude phase")

    # parameters: from the strip comment up to (and including) the Amplitude line
    paramsRe = re.compile(r"( *)<!--Disturbance strip parameters-->.*?<P>\s*Amplitude\s*=.*?</P>[^\n]*\n", re.S)
    m = paramsRe.search(text)
    if not m:
        sys.exit("Disturbance strip parameters block not found")
    text = text[:m.start()] + m.group(1) + parametersBlock(args, m.group(1)) + text[m.end():]

    noiseRe = re.compile(r'( *)<FUNCTION NAME="Noise">.*?</FUNCTION>', re.S)
    m = noiseRe.search(text)
    if not m:
        sys.exit("Noise FUNCTION not found")
    text = text[:m.start()] + m.group(1) + noiseBlock(signalU, signalV, m.group(1)) + text[m.end():]

    with open(args.session, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
